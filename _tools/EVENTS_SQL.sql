-- 1) 活动主表 ---------------------------------------------------------------
create table if not exists public.events (
  id            bigint generated by default as identity primary key,
  title         text        not null,
  content       text        not null default '',
  activity_date text        not null default '',      -- 展示用「活动日期」，YYYY-MM-DD 或自由文本
  status        text        not null default 'draft', -- draft 草稿 / published 进行中 / archived 已归档
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

-- 与 photos / submissions 同款访问模型：仅 service_role 读写（接口层全部走服务端）
alter table public.events enable row level security;
grant all on public.events to service_role;
drop policy if exists "service_role all events" on public.events;
create policy "service_role all events" on public.events
  for all to service_role using (true) with check (true);

-- 2) 报名与投稿挂接活动 -------------------------------------------------------
alter table public.submissions add column if not exists event_id bigint;
alter table public.photos     add column if not exists event_id bigint;

-- 3) （可选）常用索引：活动报名列表与活动相册按 event_id 过滤
create index if not exists idx_submissions_event on public.submissions (event_id);
create index if not exists idx_photos_event      on public.photos     (event_id);
